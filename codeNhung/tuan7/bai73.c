unsigned int read_adc(unsigned char adc_input)
{
    ADMUX = (adc_input & 0x1F) | 0x40;
    delay_us(10);
    ADCSRA |= 0x40;
    while ((ADCSRA & 0x10) == 0);
    ADCSRA |= 0x10;
    return ADCW;
}

void main(void)
{
    GLCDINIT_t glcd_init_data;
    unsigned int adc;
    unsigned int percent;

    DDRD = 0x90;
    PORTD = 0x80;
    ADMUX = 0x40;
    ADCSRA = 0x87;
    SFIOR = 0x00;

    glcd_init_data.font = font5x7;
    glcd_init_data.temp_coef = 80;
    glcd_init_data.bias = 3;
    glcd_init_data.vlcd= 55;
    glcd_init(&glcd_init_data);
    glcd_outtextxy(0,2, "DO ANH SANG");
    delay_ms(2000);
    glcd_clear();
    while (1)
    {
        adc = read_adc(7);
        percent = (unsigned int)(adc *100) /1023;
        if (percent < 40) LED = 1;
        else  LED = 0;
        if ( percent >= 50) glcd_putimagef(0,0, sun_icon, 1);
        else glcd_putimagef(0, 0 , sun_dim_icon, 1);
        glcd_line(50,0,50,48);
        sprintf(buffer, "%3d%%", percent);
        glcd_outtextxy(0,40,buffer);
        delay_ms(300);
    }
}