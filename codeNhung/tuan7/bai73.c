char buffer[20];
#define LED PORTD.4                // LED bao toi

// Doc ADC 10-bit tu kenh chi dinh
unsigned int read_adc(unsigned char adc_input)
{
    ADMUX = (adc_input & 0x1F) | 0x40;  // REFS=01 (AVCC), chon kenh
    delay_us(10);
    ADCSRA |= 0x40;                     // bat dau chuyen doi
    while ((ADCSRA & 0x10) == 0);       // cho ADIF
    ADCSRA |= 0x10;                     // xoa co
    return ADCW;
}

void main(void)
{
    GLCDINIT_t glcd_init_data;
    unsigned int adc;
    unsigned int percent;

    // PD7 = den nen GLCD, PD4 = LED bao toi
    DDRD = 0x90;
    PORTD = 0x80;                  // bat den nen, tat LED

    // Khoi tao ADC: bat, prescaler /128
    ADMUX = 0x40;
    ADCSRA = 0x87;
    SFIOR = 0x00;

    // Khoi tao GLCD 128x64
    glcd_init_data.font = font5x7;
    glcd_init_data.temp_coef = 80;
    glcd_init_data.bias = 3;
    glcd_init_data.vlcd = 55;
    glcd_init(&glcd_init_data);

    // Man hinh chao
    glcd_outtextxy(0, 2, "DO ANH SANG");
    delay_ms(2000);
    glcd_clear();

    while (1)
    {
        adc = read_adc(7);

        // Quy doi ADC -> %: adc*100/1023
        // Ep sang unsigned long truoc khi nhan de tranh tran 16-bit
        percent = (unsigned long)adc * 100 / 1023;

        // Bat LED bao toi neu < 40%
        if (percent < 40) LED = 1;
        else              LED = 0;

        // Chon icon theo do sang
        if (percent >= 50)
            glcd_putimagef(0, 0, sun_icon, 1);
        else
            glcd_putimagef(0, 0, sun_dim_icon, 1);

        // Vach phan cach doc tai x=50
        glcd_line(50, 0, 50, 48);

        // Hien % duoi icon (canh phai 3 chu so)
        sprintf(buffer, "%3d%%", percent);
        glcd_outtextxy(0, 40, buffer);

        delay_ms(300);
    }
}